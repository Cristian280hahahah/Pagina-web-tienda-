const params = new URLSearchParams(window.location.search);
const productId = params.get("producto");
const product = productDetails[productId];

const detailPage = document.querySelector("#product-detail-page");
const backLink = document.querySelector("#product-detail-back");
const category = document.querySelector("#product-detail-category");
const title = document.querySelector("#product-detail-title");
const description = document.querySelector("#product-detail-description");
const price = document.querySelector("#product-detail-price");
const availability = document.querySelector("#product-detail-availability");
const reference = document.querySelector("#product-detail-reference");
const colorSection = document.querySelector("#product-detail-colors");
const contactLink = document.querySelector("#product-detail-contact");
const imagePlaceholder = document.querySelector("#product-detail-image");

if (product) {
  const descriptionByFamily = {
    Escolar: "Un artículo práctico para acompañar las tareas y actividades de clase.",
    Papelería: "Un material útil para tus proyectos, trabajos y actividades creativas.",
    Ciber: "Consulta este servicio para recibir atención y cotización personalizada.",
  };
  const whatsappNumber = "50362011667";
  const whatsappMessage = `Hola, quiero consultar por ${product.name}.`;

  detailPage.classList.add(`product-page--${product.familyKey}`);
  document.title = `${product.name} | Librería y Papelería`;
  backLink.href = `${product.familyKey}.html`;
  backLink.textContent = `← Volver a ${product.family}`;
  category.textContent = product.category;
  title.textContent = product.name;
  description.textContent = descriptionByFamily[product.family];
  price.textContent = product.price;
  availability.textContent = product.availability;
  reference.textContent = `${product.familyKey === "ciber" ? "REF" : "SKU"}: ${product.reference}`;
  colorSection.hidden = !product.hasColors;

  if (product.image) {
    const image = document.createElement("img");
    image.src = product.image;
    image.alt = product.name;
    imagePlaceholder.replaceChildren(image);
    imagePlaceholder.removeAttribute("role");
    imagePlaceholder.removeAttribute("aria-label");
  } else {
    imagePlaceholder.setAttribute("aria-label", `Espacio para la fotografía de ${product.name.toLocaleLowerCase("es")}`);
  }

  contactLink.href = `https://wa.me/${whatsappNumber}?text=${encodeURIComponent(whatsappMessage)}`;
} else {
  document.title = "Producto no encontrado | Librería y Papelería";
  category.textContent = "Catálogo de productos";
  title.textContent = "Producto no encontrado";
  description.textContent = "No pudimos encontrar ese producto. Vuelve a la categoría para seguir explorando.";
  price.hidden = true;
  availability.hidden = true;
  reference.hidden = true;
  colorSection.hidden = true;
  contactLink.hidden = true;
}
