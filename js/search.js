const normalize = (value) =>
  value
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLocaleLowerCase("es")
    .trim();

const searchForm = document.querySelector(".search");
const searchInput = document.querySelector("#product-search");
const searchResults = document.querySelector("#product-search-results");

if (searchForm && searchInput && searchResults) {
  const findProducts = (query) => {
    const terms = normalize(query).split(/\s+/).filter(Boolean);

    if (terms.length === 0) return [];

    return productCatalog
      .filter((product) => {
        const searchableText = normalize(`${product.name} ${product.category} ${product.keywords}`);
        return terms.every((term) => searchableText.includes(term));
      })
      .sort((first, second) => {
        const normalizedQuery = normalize(query);
        const firstExact = normalize(first.name).includes(normalizedQuery) ? 0 : 1;
        const secondExact = normalize(second.name).includes(normalizedQuery) ? 0 : 1;
        return firstExact - secondExact;
      });
  };

  const hideResults = () => {
    searchResults.hidden = true;
    searchInput.setAttribute("aria-expanded", "false");
  };

  const showResults = (query) => {
    searchResults.replaceChildren();

    if (!query.trim()) {
      hideResults();
      return [];
    }

    const matches = findProducts(query);

    if (matches.length === 0) {
      const message = document.createElement("p");
      message.className = "search-results__empty";
      message.textContent = "No encontramos productos con ese nombre.";
      searchResults.append(message);
    } else {
      matches.forEach((product) => {
        const link = document.createElement("a");
        const name = document.createElement("span");
        const category = document.createElement("small");

        link.className = "search-result";
        link.href = product.href;
        name.className = "search-result__name";
        name.textContent = product.name;
        category.className = "search-result__category";
        category.textContent = product.category;
        link.append(name, category);
        searchResults.append(link);
      });
    }

    searchResults.hidden = false;
    searchInput.setAttribute("aria-expanded", "true");
    return matches;
  };

  searchInput.addEventListener("input", () => showResults(searchInput.value));

  searchForm.addEventListener("submit", (event) => {
    event.preventDefault();
    const matches = showResults(searchInput.value);

    if (matches.length > 0) {
      window.location.assign(matches[0].href);
    } else {
      searchInput.focus();
    }
  });

  searchInput.addEventListener("keydown", (event) => {
    if (event.key === "Escape") hideResults();
  });

  document.addEventListener("click", (event) => {
    if (!searchForm.contains(event.target)) hideResults();
  });
}
